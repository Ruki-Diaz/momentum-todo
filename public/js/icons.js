/** Returns an SVG markup string. Safe for innerHTML (static content only). */
function iconSvg(name, size = 16) {
  const paths = ICON_PATHS[name];
  if (!paths) return "";
  return `<svg class="icon icon-${name}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${paths}</svg>`;
}

/** Pre-rendered 14px icons for inline template use, e.g. `${ICONS.calendar}`. */
const ICONS = Object.fromEntries(Object.keys(ICON_PATHS).map((k) => [k, iconSvg(k, 14)]));

/** Returns a detached SVG element (for DOM-built UI). */
function iconEl(name, size = 16) {
  const tpl = document.createElement("template");
  tpl.innerHTML = iconSvg(name, size);
  return tpl.content.firstElementChild;
}
